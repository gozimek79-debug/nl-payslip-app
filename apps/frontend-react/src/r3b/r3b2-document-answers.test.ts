import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createR3BStore, panelRows, resultReasons, type R3BStore, type ThreadMessage } from './r3b-flow.ts';
import { describeTurn, documentAnswerLines } from './r3b-describe.ts';
import { R3B_COPY } from './r3b-copy.ts';
import { withoutDocumentValues, type ScenarioView, type TurnResultView } from './r3b-turn.ts';
import { fixtures, harness, pdf, readByRef, response, type Recorded } from './r3b-test-support.ts';

/**
 * R3-B.2 through the real interface state machine: a payslip read BY REFERENCE (the reader route's server-held batch
 * references), the profile's server-held document context, and conversation turns that name that context - replayed
 * against the recorded real backend (fixtures generated by apps/backend-node/src/conversation/r3b-document-first.test.ts).
 * The interface sends references only - never batch JSON, never a document value of its own.
 */

const PL = R3B_COPY.pl;
const EN = R3B_COPY.en;
const CONTEXT_REF = fixtures.documentRefs.context;
type TurnBlock = Extract<ThreadMessage['block'], { kind: 'turn' }>;
const turnBlocks = (store: R3BStore) => store.getState().messages.map((m) => m.block).filter((b): b is TurnBlock => b.kind === 'turn');
const PUBLIC_TURN_KEYS = ['scenario', 'message', 'locale', 'conversation', 'documentContextRef'];

async function readWeek41(turns: Recorded[], lang: 'pl' | 'en' = 'pl') {
  const h = harness({ reads: { 'loonstrook-week41.pdf': readByRef('payslip_week41_1555') }, turns });
  const store = createR3BStore(h.deps, lang);
  store.addFiles([pdf('loonstrook-week41.pdf')], 'payslip');
  await store.read();
  return { h, store };
}

test('R3-B.2: the documents go to the profile BY REFERENCE and the server-held context is kept (its reference only)', async () => {
  const { h, store } = await readWeek41([]);
  const [body] = h.resolveBodies as Array<{ documents: Array<Record<string, unknown>> }>;
  assert.deepEqual(body?.documents.map((d) => [d.batchRefs, d.factBatches]), [[fixtures.documentRefs.batch.payslip_week41_1555, undefined]], 'references, never the batch JSON');
  const s = store.getState();
  assert.equal(s.documentContext?.ref, CONTEXT_REF);
  assert.equal(s.phase, 'goal');
  const summary = s.messages.map((m) => m.block).find((b) => b.kind === 'summary') as Extract<ThreadMessage['block'], { kind: 'summary' }>;
  assert.deepEqual(summary.printed?.filter((f) => ['net', 'payout', 'reimbursement'].includes(f.key)).map((f) => [f.key, f.value]), [['net', 509.92], ['payout', 584.92], ['reimbursement', 75]]);
  assert.equal(s.knowledge?.facts.find((f) => f.path === 'employment.hourlyRate')?.value, 15.55, 'the 15.55 payslip rate reaches the profile');
});

test('R3-B.2: "Jaka jest moja stawka?", "Ile faktycznie przelano?", "Dlaczego netto jest niższe?" are answered from the document; the rate is never asked', async () => {
  const { h, store } = await readWeek41(fixtures.turns.r3b2_document_questions as Recorded[]);
  for (const message of ['Jaka jest moja stawka?', 'Ile faktycznie przelano?', 'Dlaczego netto jest niższe?', 'Ile dostanę za 40 godzin?', '40 godzin od poniedziałku do piątku']) await store.send(message);
  assert.equal(h.remainingTurns(), 0, 'every recorded turn was sent exactly as recorded');

  // The requests: public fields + the opaque context reference; a document value only as the server itself wrote it.
  let previous: ScenarioView | undefined;
  for (const body of h.turnBodies) {
    assert.deepEqual(Object.keys(body).filter((k) => !PUBLIC_TURN_KEYS.includes(k)), []);
    assert.equal(body.documentContextRef, CONTEXT_REF);
    assert.ok(!/factBatches|batchRefs|Uurloon|Loon normaal|Overgemaakt/.test(JSON.stringify(body)), 'no document content in a turn');
    assert.deepEqual(body.scenario, previous, 'the Scenario is sent back exactly as the server returned it');
    previous = (turnBlocks(store)[h.turnBodies.indexOf(body)]?.result as TurnResultView).scenario;
  }

  const blocks = turnBlocks(store);
  const answer = (i: number) => documentAnswerLines(blocks[i]?.result.documentAnswer as NonNullable<TurnResultView['documentAnswer']>, store.getState().docs, PL, 'pl');
  assert.deepEqual(answer(0).items, ['Stawka godzinowa: €15,55/h („Uurloon”) — Pasek wypłaty 1, week 41/2026']);
  assert.deepEqual(answer(1).items, [
    'Netto: €509,92 („Totaal netto”) — Pasek wypłaty 1, week 41/2026',
    'Przelano na konto: €584,92 („Overgemaakt”) — Pasek wypłaty 1, week 41/2026',
    'Zwrot kosztów: €75,00 („Onb. Reiskosten”) — Pasek wypłaty 1, week 41/2026',
  ]);
  assert.ok(answer(1).notes.includes(PL.answer.note), 'labelled as a reading, not a Loonto calculation');
  assert.ok(answer(2).notes.includes(PL.answer.whyNet), 'why-net: printed lines side by side - no computed difference');
  assert.ok(answer(2).items.some((line) => line.startsWith('Dodatek (procent): 1,54% („ADV toeslag”)')), 'ADV is shown as its own surcharge line');

  assert.ok(blocks.every((b) => b.result.nextQuestion?.field !== 'pay.hourlyRate'), 'the document rate is never asked');
  const first = describeTurn(blocks[0] as TurnBlock, PL, 'pl');
  assert.ok(first.question?.startsWith(PL.answer.backTo), 'after the answer the conversation simply continues');
  const calc = describeTurn(blocks[3] as TurnBlock, PL, 'pl');
  assert.ok(calc.lines.includes(PL.turn.rateFromDocument('€15,55/h')), '"Ile dostanę za 40 godzin?" does not re-ask the rate');
  assert.ok(calc.lines.includes(PL.turn.calculationGated), 'and explains that the amount stays gated');
  assert.equal(blocks[3]?.result.nextQuestion?.kind, 'clarify_hours_composition');

  const s = store.getState();
  const rateRow = panelRows(s).find((r) => r.field === 'pay.hourlyRate');
  assert.deepEqual([rateRow?.node?.state, rateRow?.node?.source, rateRow?.node?.value], ['known', 'document', 15.55], 'the server wrote the trusted document rate');
  assert.ok(resultReasons(s).some((r) => r.key === 'documentProvisional'), 'still a provisional reading - no amount');
  assert.notEqual(s.evaluation?.status, 'computed');
});

