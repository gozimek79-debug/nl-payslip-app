test('R3-B.2: an expired server context fails closed - its document values leave the Scenario, the documents wait for a new read, the message is resent without it', async () => {
  const recorded = fixtures.turns.r3b2_document_questions as Recorded[];
  const h = harness({ reads: { 'loonstrook-week41.pdf': readByRef('payslip_week41_1555') }, turns: [recorded[0] as Recorded] });
  const turnBodies: Array<Record<string, unknown>> = [];
  const base = h.deps.fetchImpl;
  const fallbackResponse = structuredClone((recorded[0] as Recorded).response) as TurnResultView;
  fallbackResponse.scenario = withoutDocumentValues(fallbackResponse.scenario) as ScenarioView;
  fallbackResponse.documentAnswer = { available: false, topics: ['payout'], items: [] };
  const deps = {
    ...h.deps,
    fetchImpl: (async (url: string, init?: RequestInit) => {
      if (url !== '/api/scenario/turn' || h.remainingTurns() > 0) return base(url, init);
      const body = JSON.parse(String(init?.body)) as Record<string, unknown>;
      turnBodies.push(body);
      return body.documentContextRef ? response(409, { error_code: 'document_context_invalid' }) : response(200, fallbackResponse);
    }) as unknown as typeof fetch,
  };
  const store = createR3BStore(deps, 'pl');
  store.addFiles([pdf('loonstrook-week41.pdf')], 'payslip');
  await store.read();
  await store.send('Jaka jest moja stawka?');
  assert.equal(store.getState().scenario?.pay.hourlyRate !== undefined, true, 'the server wrote the document rate');

  await store.send('Ile faktycznie przelano?');
  assert.equal(turnBodies.length, 2, 'refused once (409), then resent once');
  assert.equal(turnBodies[0]?.documentContextRef, CONTEXT_REF);
  assert.equal(turnBodies[1]?.documentContextRef, undefined, 'the resend names no context');
  assert.equal((turnBodies[1]?.scenario as ScenarioView).pay.hourlyRate, undefined, 'a value the server can no longer back is not sent (it would be self-declared)');
  const s = store.getState();
  assert.equal(s.documentContext, null);
  assert.deepEqual(s.docs.map((d) => [d.status, d.batchRefs]), [['selected', null]], 'the document waits for a new explicit read');
  assert.ok(s.messages.some((m) => m.block.kind === 'note' && m.block.note === 'context_expired'));
  const last = turnBlocks(store).at(-1) as TurnBlock;
  assert.deepEqual(documentAnswerLines(last.result.documentAnswer as NonNullable<TurnResultView['documentAnswer']>, s.docs, PL, 'pl').notes, [PL.answer.noContext]);
});

test('R3-B.2: when the server no longer holds the batches, the profile still resolves from the echoed batches - but without any document context', async () => {
  const byRef = fixtures.profiles.payslip_week41_by_ref as Recorded;
  const bodies: Array<{ documents: Array<Record<string, unknown>> }> = [];
  const h = harness({ reads: { 'loonstrook-week41.pdf': readByRef('payslip_week41_1555') } });
  const deps = {
    ...h.deps,
    fetchImpl: (async (url: string, init?: RequestInit) => {
      const body = JSON.parse(String(init?.body)) as { documents: Array<Record<string, unknown>> };
      assert.equal(url, '/api/profile/resolve');
      bodies.push(body);
      if (body.documents.some((d) => d.batchRefs)) return response(409, { error_code: 'document_reference_invalid' });
      return response(200, { ...(byRef.response as object), documentContext: null });
    }) as unknown as typeof fetch,
  };
  const store = createR3BStore(deps, 'pl');
  store.addFiles([pdf('loonstrook-week41.pdf')], 'payslip');
  await store.read();
  assert.deepEqual(bodies.map((b) => b.documents.map((d) => [Boolean(d.batchRefs), Array.isArray(d.factBatches)])), [[[true, false]], [[false, true]]]);
  const s = store.getState();
  assert.equal(s.documentContext, null, 'echoed batches are never trusted');
  assert.equal(s.knowledge?.facts.find((f) => f.path === 'employment.hourlyRate')?.value, 15.55, 'the summary still works');
  assert.deepEqual(s.docs.map((d) => d.batchRefs), [null]);
});

